    private void tambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahActionPerformed

    String pasien = namapasien.getSelectedItem().toString();
    String catat = text.getText();

    java.util.Date tgl = tanggal.getDate();
    java.sql.Date tanggal = new java.sql.Date(tgl.getTime());

    try {
        String sql = "INSERT INTO laporan_konsultasi (tanggal, nama_pasien, catat) VALUES (?, ?, ?)";
        Connection conn = koneksi.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setDate(1, tanggal);
        pst.setString(2, pasien);
        pst.setString(3, catat);

        pst.executeUpdate();
        JOptionPane.showMessageDialog(this, "Laporan berhasil disimpan");

        loadData();
        text.setText("");

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }

    }//GEN-LAST:event_tambahActionPerformed

    private void cetakActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cetakActionPerformed
   try {
        HashMap<String, Object> param = new HashMap<>();

        // panggil file jasper dari classpath
        InputStream report = getClass()
                .getResourceAsStream("/laporan/konsultasi.jasper");

        if (report == null) {
            JOptionPane.showMessageDialog(this, "File laporan tidak ditemukan");
            return;
        }

        Connection conn = koneksi.getConnection();

        JasperPrint jp =
                JasperFillManager.fillReport(report, param, conn);

        JasperViewer.viewReport(jp, false);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this,
                "Gagal mencetak laporan\n" + e.getMessage());
    }

    }//GEN-LAST:event_cetakActionPerformed

    private void cariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cariActionPerformed
   String keyword = cari.getText();

    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("id");
    model.addColumn("tanggal");
    model.addColumn("nama_pasien");
    model.addColumn("catat");

    try {
        String sql = "SELECT id, tanggal, nama_pasien, catat FROM laporan_konsultasi WHERE nama LIKE ?";
        Connection conn = koneksi.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);

        pst.setString(1, "%" + keyword + "%");
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getDate("tanggal"),   // atau rs.getString("tanggal")
                rs.getString("nama_pasien"),
                rs.getString("catat")
            });
        }

        jTable.setModel(model);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal cari: " + e.getMessage());
    }

    }//GEN-LAST:event_cariActionPerformed


