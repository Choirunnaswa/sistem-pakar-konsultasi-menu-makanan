    private void loadNamaPasien() {
    try {
        String sql = "SELECT username FROM pengguna";
        Connection conn = koneksi.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        namapasien.removeAllItems();
        while (rs.next()) {
            namapasien.addItem(rs.getString("username"));
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load nama pasien");
    }
}
    private void loadData() {
    DefaultTableModel model = (DefaultTableModel) jTable.getModel();
    model.setRowCount(0);

    try {
        String sql = "SELECT * FROM laporan_konsultasi";
        Connection conn = koneksi.getConnection();
        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getInt("id"),
                rs.getDate("tanggal"),
                rs.getString("nama_pasien"),
                rs.getString("catat")
            });
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Gagal load laporan");
    }
}
